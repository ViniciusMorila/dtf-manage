from pathlib import Path
import subprocess
import sys
import threading
import time


def _run_application(*, development_no_auth=False) -> int:
    from dtf_manager.core import auth_timing
    auth_timing.start_application()
    with auth_timing.span("bootstrap_ui_import"):
        from dtf_manager.core.bootstrap import run_application

    return run_application(development_no_auth=development_no_auth)


def _run_with_auto_reload(*, development_no_auth=False) -> int:
    try:
        from watchdog.events import FileSystemEventHandler
        from watchdog.observers import Observer
    except ImportError:
        return _run_application(development_no_auth=development_no_auth)

    reload_requested = threading.Event()

    class PythonChangeHandler(FileSystemEventHandler):
        def on_any_event(self, event) -> None:
            # Importing a module can generate file-open/file-close events. Those
            # are reads, not source changes, and must not restart the application.
            if event.is_directory or event.event_type not in {"modified", "created", "moved"}:
                return
            changed_path = getattr(event, "dest_path", "") or event.src_path
            if Path(changed_path).suffix.lower() == ".py":
                reload_requested.set()

    project_path = Path(__file__).resolve().parent
    observer = Observer()
    observer.schedule(PythonChangeHandler(), str(project_path), recursive=True)
    observer.start()
    try:
        while True:
            command = [sys.executable, str(Path(__file__).resolve()), "--no-reload"]
            if development_no_auth:
                command.append("--no-auth")
            child = subprocess.Popen(
                command,
                cwd=project_path,
            )
            while child.poll() is None and not reload_requested.wait(0.2):
                pass
            if child.poll() is not None and not reload_requested.is_set():
                return child.returncode or 0

            child.terminate()
            try:
                child.wait(timeout=3)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait()

            # Group the several filesystem events generated by a single save.
            time.sleep(0.35)
            reload_requested.clear()
    except KeyboardInterrupt:
        return 0
    finally:
        observer.stop()
        observer.join()


if __name__ == "__main__":
    if "--self-check" in sys.argv:
        # Headless verification of SMBIOS and DPAPI (also used on the frozen build).
        index = sys.argv.index("--self-check")
        report_path = sys.argv[index + 1] if len(sys.argv) > index + 1 else "dtf_self_check.json"
        from dtf_manager.core import self_check
        raise SystemExit(self_check.run(report_path))
    # Reloading is a development-only opt-in. The normal application process
    # must never restart because importing a spreadsheet dependency touched a
    # file monitored by Windows/OneDrive.
    auto_reload = "--reload" in sys.argv and not getattr(sys, "frozen", False)
    development_no_auth = "--no-auth" in sys.argv and not getattr(sys, "frozen", False)
    if development_no_auth:
        from dtf_manager.core import config
        if not config.no_auth_allowed():
            print("--no-auth exige a variavel de ambiente DTF_ALLOW_NO_AUTH=1 "
                  "(uso exclusivo de desenvolvimento).", file=sys.stderr)
            raise SystemExit(2)
    if auto_reload:
        raise SystemExit(_run_with_auto_reload(development_no_auth=development_no_auth))
    raise SystemExit(_run_application(development_no_auth=development_no_auth))
